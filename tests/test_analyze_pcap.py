"""Regression tests for the SWYNEX PCAP analyzer.

Run from the repository root with:
    python -m unittest discover -s tests -v

These tests use only the synthetic capture generated by make_sample_pcap.py.
No network traffic is sent or captured.
"""
import pathlib
import subprocess
import sys
import tempfile
import unittest

ROOT = pathlib.Path(__file__).resolve().parents[1]
GENERATOR = ROOT / "make_sample_pcap.py"
ANALYZER = ROOT / "analyze_pcap.py"


class AnalyzerCliTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.workdir = pathlib.Path(self.temp.name)
        generated = subprocess.run(
            [sys.executable, str(GENERATOR)],
            cwd=self.workdir,
            text=True,
            capture_output=True,
            check=False,
        )
        self.assertEqual(generated.returncode, 0, generated.stderr)
        self.capture = self.workdir / "sample_lab_traffic.pcap"
        self.assertTrue(self.capture.is_file())

    def tearDown(self):
        self.temp.cleanup()

    def test_synthetic_capture_has_expected_packet_count_and_protocols(self):
        result = subprocess.run(
            [sys.executable, str(ANALYZER), str(self.capture)],
            text=True,
            capture_output=True,
            check=False,
        )
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertIn("Total packets: **39**", result.stdout)
        self.assertIn("| TCP | 33 |", result.stdout)
        self.assertIn("| UDP | 4 |", result.stdout)
        self.assertIn("| ARP | 2 |", result.stdout)

    def test_synthetic_capture_exercises_expected_detection_rules(self):
        result = subprocess.run(
            [sys.executable, str(ANALYZER), str(self.capture)],
            text=True,
            capture_output=True,
            check=False,
        )
        self.assertEqual(result.returncode, 0, result.stderr)
        expected_indicators = (
            "Possible credentials in cleartext",
            "Possible port scan",
            "ARP anomaly",
            "Cleartext HTTP traffic",
            "Cleartext FTP traffic",
            "Unusually long DNS label",
        )
        for indicator in expected_indicators:
            with self.subTest(indicator=indicator):
                self.assertIn(indicator, result.stdout)

    def test_truncated_capture_fails_with_clear_error(self):
        broken = self.workdir / "broken.pcap"
        broken.write_bytes(bytes.fromhex("d4c3b2a1"))
        result = subprocess.run(
            [sys.executable, str(ANALYZER), str(broken)],
            text=True,
            capture_output=True,
            check=False,
        )
        self.assertNotEqual(result.returncode, 0)
        self.assertIn("Truncated pcap global header", result.stderr)
        self.assertNotIn("Traceback", result.stderr)

    def test_output_option_writes_markdown_report(self):
        output = self.workdir / "findings.md"
        result = subprocess.run(
            [sys.executable, str(ANALYZER), str(self.capture), "-o", str(output)],
            text=True,
            capture_output=True,
            check=False,
        )
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertTrue(output.is_file())
        self.assertIn("Total packets: **39**", output.read_text(encoding="utf-8"))


if __name__ == "__main__":
    unittest.main()
